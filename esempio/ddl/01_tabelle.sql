CREATE TABLE VENDITE.CLIENTE (
  ID_CLIENTE      NUMBER(10)      NOT NULL,
  RAGIONE_SOCIALE VARCHAR2(200 CHAR) NOT NULL,
  PARTITA_IVA     VARCHAR2(11),
  FLG_ATTIVO      CHAR(1)         DEFAULT 'S' NOT NULL,
  TIPO_CLIENTE    VARCHAR2(3),
  DT_INSERIMENTO  DATE            DEFAULT SYSDATE NOT NULL,
  NOTE            CLOB,
  CONSTRAINT PK_CLIENTE PRIMARY KEY (ID_CLIENTE),
  CONSTRAINT CK_CLIENTE_ATTIVO CHECK (FLG_ATTIVO IN ('S','N'))
);

CREATE TABLE STATO_ORDINE (
  COD_STATO   VARCHAR2(2) PRIMARY KEY,
  DESCRIZIONE VARCHAR2(100) NOT NULL
);

CREATE TABLE "ORDINE" (
  ID_ORDINE   NUMBER(12) NOT NULL,
  ID_CLIENTE  NUMBER(10) NOT NULL,
  DT_ORDINE   DATE DEFAULT SYSDATE,
  COD_STATO   VARCHAR2(2) DEFAULT 'IN' NOT NULL,
  TOTALE      NUMBER(12,2),
  CONSTRAINT PK_ORDINE PRIMARY KEY (ID_ORDINE)
);

ALTER TABLE ORDINE ADD CONSTRAINT FK_ORDINE_CLIENTE FOREIGN KEY (ID_CLIENTE) REFERENCES CLIENTE (ID_CLIENTE);
ALTER TABLE ORDINE ADD CONSTRAINT FK_ORDINE_STATO FOREIGN KEY (COD_STATO) REFERENCES STATO_ORDINE(COD_STATO);

CREATE TABLE PRODOTTO (
  ID_PRODOTTO NUMBER(10) CONSTRAINT PK_PRODOTTO PRIMARY KEY,
  CODICE      VARCHAR2(30) NOT NULL UNIQUE,
  DESCRIZIONE VARCHAR2(200),
  PREZZO      NUMBER(10,2) NOT NULL,
  FLG_DISMESSO CHAR(1) DEFAULT 'N'
);

CREATE TABLE RIGA_ORDINE (
  ID_ORDINE   NUMBER(12) NOT NULL REFERENCES ORDINE(ID_ORDINE) ON DELETE CASCADE,
  NUM_RIGA    NUMBER(4)  NOT NULL,
  ID_PRODOTTO NUMBER(10) NOT NULL,
  QUANTITA    NUMBER(8)  NOT NULL,
  PREZZO_UNIT NUMBER(10,2),
  CONSTRAINT PK_RIGA_ORDINE PRIMARY KEY (ID_ORDINE, NUM_RIGA),
  CONSTRAINT FK_RIGA_PRODOTTO FOREIGN KEY (ID_PRODOTTO) REFERENCES PRODOTTO (ID_PRODOTTO)
);

CREATE TABLE LOG_ATTIVITA (
  ID_LOG NUMBER(12),
  DT_LOG TIMESTAMP(6) WITH TIME ZONE,
  MESSAGGIO VARCHAR2(4000)
);

CREATE INDEX IX_ORDINE_CLIENTE ON ORDINE (ID_CLIENTE);
CREATE INDEX IX_ORDINE_DATA ON ORDINE (DT_ORDINE DESC);

COMMENT ON TABLE CLIENTE IS 'Anagrafica dei clienti dell''azienda';
COMMENT ON COLUMN CLIENTE.FLG_ATTIVO IS 'S = attivo, N = disattivato';
COMMENT ON COLUMN VENDITE.ORDINE.COD_STATO IS 'Stato corrente dell''ordine, vedi STATO_ORDINE';

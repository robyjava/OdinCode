CREATE SEQUENCE SEQ_ORDINE START WITH 1 INCREMENT BY 1 CACHE 20;

CREATE OR REPLACE VIEW V_ORDINI_APERTI AS
SELECT o.ID_ORDINE, c.RAGIONE_SOCIALE, o.TOTALE
  FROM ORDINE o JOIN CLIENTE c ON c.ID_CLIENTE = o.ID_CLIENTE
 WHERE o.COD_STATO <> 'CH';

CREATE OR REPLACE TRIGGER TRG_ORDINE_BI
BEFORE INSERT ON ORDINE
FOR EACH ROW
BEGIN
  IF :NEW.ID_ORDINE IS NULL THEN
    :NEW.ID_ORDINE := SEQ_ORDINE.NEXTVAL;
  END IF;
END;
/

CREATE OR REPLACE PACKAGE BODY PKG_ORDINI AS
  PROCEDURE CHIUDI_SCADUTI(p_giorni IN NUMBER) IS
  BEGIN
    UPDATE ORDINE SET COD_STATO = 'CH' WHERE DT_ORDINE < SYSDATE - p_giorni AND COD_STATO = 'IN';
    INSERT INTO LOG_ATTIVITA (ID_LOG, DT_LOG, MESSAGGIO) VALUES (1, SYSTIMESTAMP, 'chiusura');
  END;
END PKG_ORDINI;
/
